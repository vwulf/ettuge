#!/usr/bin/env python3
"""Regenerate MiniLean/Checks.lean: pin every output the literate pages show.

Runs each page through `lake env lean --json`, matches every info message to
the `#mini_…` command that produced it (with any indented
continuation lines), and writes that command
inside `#guard_msgs` with its expected output. Run from src/main/lean/minilean
after changing a page or the kernel's printing, then review the diff.
"""
import json
import subprocess
import sys
from pathlib import Path

PAGES = ["MiniLean/Prelude.lean"] + sorted(
    str(p) for p in Path("MiniLean/Walkthrough").glob("S*.lean")) + [
    "MiniLean/StepByStep.lean"]

HEADER = '''import MiniLean.Prelude
import MiniLean.Walkthrough
import MiniLean.StepByStep

/-!
# Pinned outputs

The prelude and the walkthrough pages show MiniLean's output under each
command. This module re-runs every one of those commands inside `#guard_msgs`
with the expected output written out, so `lake build` fails if any of it
changes. It is generated by `scripts/gen_checks.py` and left off the literate
site.
-/

'''


def outputs(page):
    run = subprocess.run(["lake", "env", "lean", "--json", page],
                         capture_output=True, text=True)
    lines = Path(page).read_text().splitlines()
    found = []
    for raw in run.stdout.splitlines():
        try:
            msg = json.loads(raw)
        except json.JSONDecodeError:
            continue
        if msg.get("severity") != "information":
            sys.exit(f"{page}: unexpected {msg.get('severity')}: {msg.get('data')}")
        line = msg["pos"]["line"]
        cmd = lines[line - 1]
        if not cmd.startswith("#mini_"):
            sys.exit(f"{page}:{line}: output from a command that is not a #mini_ command")
        # a command continues on the indented lines after it (a tactic block)
        i = line
        while i < len(lines) and lines[i].startswith(" "):
            cmd += "\n" + lines[i]
            i += 1
        found.append((cmd, msg["data"].rstrip("\n")))
    return found


def main():
    out = [HEADER]
    for page in PAGES:
        out.append(f"/-! ## `{page}` -/\n\n")
        for cmd, data in outputs(page):
            out.append(f"/--\ninfo: {data}\n-/\n#guard_msgs in\n{cmd}\n\n")
    Path("MiniLean/Checks.lean").write_text("".join(out).rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
